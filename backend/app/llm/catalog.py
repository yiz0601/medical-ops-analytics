DATASET_WINDOW: tuple[str, str] = ("2025-04-01", "2025-06-30")


def metric_name(code: str) -> str:
    return METRIC_CATALOG.get(code, (code, "", ""))[0]


def dept_name(code: str) -> str:
    return DEPT_CATALOG.get(code, code)


def metric_meta() -> list[dict[str, str]]:
    """指标元数据列表（供 Prompt 注入）。"""
    return [
        {"code": code, "name": name, "theme": theme, "unit": unit}
        for code, (name, theme, unit) in METRIC_CATALOG.items()
    ]


def dim_schema() -> list[dict[str, str]]:
    """维度元数据（供 Prompt 注入）。"""
    return [
        {"dim_type": "dept", "dim_value": code, "dim_name": name}
        for code, name in DEPT_CATALOG.items()
    ] + [
        {"dim_type": "granularity", "dim_value": value, "dim_name": value}
        for value in ("day", "month", "period")
    ]
